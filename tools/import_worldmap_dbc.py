"""Generate Database/worldmap.lua from the OctoWoW client's own map tables.

    py -3.10 -I tools/import_worldmap_dbc.py [--data C:/Games/Wow-Octo/Data]

Reads DBFilesClient\\WorldMapContinent.dbc and DBFilesClient\\WorldMapArea.dbc
out of the client MPQs (needs the `mpyq` package) and writes, for every zone
row on a continent map, where that zone's map sits on its continent map as
UV fractions. The continent world map can then place a zone's database
percentages: u = left + x / 100 * width, v = top + y / 100 * height.

Later archives override earlier ones, like the client does. Archives this
reader cannot open (encrypted Turtle patches) are skipped and listed in the
output header: a zone they reworked can be out of date here. The runtime
therefore keeps a zone only while its yard size here matches
Database/minimap.lua (see MapContext:GetContinentZoneTransform).
"""
import argparse
import os
import struct
import sys

ARCHIVES = ["dbc.MPQ", "patch.MPQ", "patch-1.mpq", "patch-2.mpq",
            "patch-3.mpq", "patch-4.mpq", "patch-5.mpq"]
AREA_FILE = "DBFilesClient\\WorldMapArea.dbc"
CONTINENT_FILE = "DBFilesClient\\WorldMapContinent.dbc"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Database", "worldmap.lua")


def read_newest(data_dir, name):
    import mpyq
    found, source, skipped = None, None, []
    for archive in ARCHIVES:
        path = os.path.join(data_dir, archive)
        if not os.path.exists(path):
            continue
        try:
            mpq = mpyq.MPQArchive(path, listfile=True)
        except Exception as error:  # encrypted Turtle patches
            skipped.append("%s (%s)" % (archive, error))
            continue
        if mpq.files and name.encode() in mpq.files:
            blob = mpq.read_file(name)
            if blob:
                found, source = blob, archive
    if found is None:
        sys.exit("%s not found in %s" % (name, data_dir))
    return found, source, skipped


def records(blob):
    magic, count, fields, size, _ = struct.unpack("<4s4i", blob[:20])
    if magic != b"WDBC":
        sys.exit("not a WDBC file")
    strings = blob[20 + count * size:]
    for index in range(count):
        raw = blob[20 + index * size:20 + (index + 1) * size]
        yield (struct.unpack("<%di" % fields, raw),
               struct.unpack("<%df" % fields, raw), strings)


def text(strings, offset):
    end = strings.index(b"\0", offset)
    return strings[offset:end].decode("utf-8")


def number(value, places):
    out = ("%." + str(places) + "f") % value
    out = out.rstrip("0").rstrip(".")
    return "0" if out in ("-0", "") else out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default=r"C:\Games\Wow-Octo\Data")
    args = parser.parse_args()

    continent_blob, continent_source, skipped = read_newest(args.data, CONTINENT_FILE)
    area_blob, area_source, _ = read_newest(args.data, AREA_FILE)

    # WorldMapContinent: ID, MapID, ... -- the maps the client calls continents.
    continent_maps = set(ints[1] for ints, _, _ in records(continent_blob))

    continents = {}   # mapId -> (file, left, right, top, bottom)
    zones = []        # (areaId, mapId, file, left, right, top, bottom)
    for ints, floats, strings in records(area_blob):
        map_id, area_id = ints[1], ints[2]
        if map_id not in continent_maps:
            continue
        name = text(strings, ints[3])
        rect = floats[4:8]
        if area_id == 0:
            continents[map_id] = (name,) + tuple(rect)
        else:
            zones.append((area_id, map_id, name) + tuple(rect))

    lines = [
        "-- PandaQuest bundled world data. GENERATED by tools/import_worldmap_dbc.py; do not edit.",
        "-- Source: the OctoWoW client's own DBFilesClient\\WorldMapArea.dbc (%s) and" % area_source,
        "-- WorldMapContinent.dbc (%s). Game data (c) Blizzard Entertainment." % continent_source,
    ]
    for entry in skipped:
        lines.append("-- Not readable, so not applied: %s." % entry)
    lines += [
        "-- continents: map file name (GetMapInfo on a continent view) -> continent map ID.",
        "-- zones: [areaId] = { continent map ID, left u, top v, width u, height v,",
        "--   width yards, height yards } -- the zone map's rectangle on its continent map.",
        'PandaQuestData["worldmap"] = {',
        '  source = "%s",' % area_source,
        "  continents = {",
    ]
    for map_id in sorted(continents):
        lines.append('    ["%s"] = %d,' % (continents[map_id][0], map_id))
    lines.append("  },")
    lines.append("  zones = {")
    seen = set()
    for area_id, map_id, name, left, right, top, bottom in sorted(zones):
        continent = continents.get(map_id)
        if not continent or area_id in seen:
            continue
        _, c_left, c_right, c_top, c_bottom = continent
        c_width, c_height = c_left - c_right, c_top - c_bottom
        width, height = left - right, top - bottom
        if c_width <= 0 or c_height <= 0 or width <= 0 or height <= 0:
            continue
        seen.add(area_id)
        lines.append("    [%d]={%d,%s,%s,%s,%s,%s,%s}, -- %s" % (
            area_id, map_id,
            number((c_left - left) / c_width, 6), number((c_top - top) / c_height, 6),
            number(width / c_width, 6), number(height / c_height, 6),
            number(width, 2), number(height, 2), name))
    lines.append("  },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote %s: %d continents, %d zones (from %s)" % (
        os.path.normpath(OUT), len(continents), len(seen), area_source))


if __name__ == "__main__":
    main()
